#!/usr/bin/env node
/**
 * Emits the SQL that the raw-SQL era applied to production after the last
 * Prisma migration (2026-03-23), by extracting the DDL from the application
 * code that actually ran it.
 *
 * This is a prediction, not the authority. `prisma db pull` against production
 * is the authority. Diffing the two is the point: anything in production that
 * this does not predict is something nobody wrote down.
 *
 * Every statement is IF NOT EXISTS, so the same migration is a no-op against
 * production and a real create against a fresh database.
 */
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');

let src = '';
for (const f of fs.readdirSync(ROOT)) {
  if (f.endsWith('.js') && f !== 'node_modules') src += fs.readFileSync(path.join(ROOT, f), 'utf8') + '\n';
}

const out = [];
const seen = new Set();
const push = (s) => { const k = s.replace(/\s+/g, ' '); if (!seen.has(k)) { seen.add(k); out.push(s); } };

// CREATE TABLE blocks, taken verbatim from the code that created them
for (const m of src.matchAll(/CREATE TABLE IF NOT EXISTS\s+"?[A-Za-z_]+"?\s*\([\s\S]*?\n\s*\)\s*;?/g)) {
  push(m[0].replace(/^\s+/gm, '  ').trim().replace(/;?$/, ';'));
}
// ALTER TABLE ... ADD COLUMN, excluding the templated one
for (const m of src.matchAll(/ALTER TABLE "[A-Za-z_]+" ADD COLUMN IF NOT EXISTS "[A-Za-z_]+"[^`;]*/g)) {
  const s = m[0].trim().replace(/\s+/g, ' ');
  if (s.includes('${')) continue;
  push(s.replace(/;?$/, ';'));
}
// the templated Lead attribution loop
const attr = [...src.matchAll(/\['([a-zA-Z]+)', *'([A-Z]+)'\]/g)].map((m) => [m[1], m[2]]);
for (const [col, type] of attr) {
  push(`ALTER TABLE "Lead" ADD COLUMN IF NOT EXISTS "${col}" ${type};`);
}
// indexes created alongside
for (const m of src.matchAll(/CREATE (?:UNIQUE )?INDEX IF NOT EXISTS[^`;]*/g)) {
  push(m[0].trim().replace(/\s+/g, ' ').replace(/;?$/, ';'));
}

const header = `-- Reconciliation: raw-SQL production changes made after the last Prisma
-- migration (20260323000000_add_waitlist_request).
--
-- Every statement is IF NOT EXISTS. Against production, where all of these
-- objects already exist, this is a no-op and is marked applied with
-- \`prisma migrate resolve --applied\`. Against a fresh database it creates
-- them, so migrations alone reproduce the production structure.
--
-- Generated by scripts/build-reconciliation-sql.js from the application code
-- that originally issued this DDL. Verify against \`prisma db pull\`.
`;
console.log(header + '\n' + out.join('\n\n'));
console.error(`-- ${out.length} statements`);
